import time  # Импортируем стандартный модуль time для работы с временем (например, для пауз между действиями).
from dask.distributed import Client  # Импортируем класс Client из библиотеки Dask для подключения к распределенной вычислительной системе.

# Создаем клиентское соединение с Scheduler (распределенным планировщиком задач).
client = Client('tcp://127.0.0.1:8786')
# Здесь мы подключаемся к серверу Dask, который работает на локальной машине по адресу 127.0.0.1 и порту 8786.
# Это позволяет запускать задачи в распределенной среде Dask, которая управляет распределением задач между различными рабочими узлами (workers).

# Функция, имитирующая длительную задачу, которая "спит" заданное количество секунд.
def long_running_task(seconds):
    print(f"Starting task for {seconds} seconds...")  # Выводим сообщение о начале задачи с указанием времени ожидания.
    time.sleep(seconds)  # "Спим" указанное количество секунд, имитируя длительную задачу.
    print("Task completed!")  # Выводим сообщение о завершении задачи.
    return f"Task took {seconds} seconds to complete."  # Возвращаем строку с результатом задачи.

# Отправляем задачу на выполнение в распределенной среде.
future = client.submit(long_running_task, 10)
# В этой строке задача `long_running_task` отправляется на выполнение с параметром 10 (то есть она будет "спать" 10 секунд).
# Метод `submit` отправляет задачу в Dask для выполнения. Возвращаемое значение `future` — это объект Future,
# который будет содержать результат выполнения задачи, когда она завершится.

# Периодическая проверка статуса выполнения задачи.
# Этот цикл будет выполняться до тех пор, пока задача, представленная объектом Future (в данном случае future), не будет завершена.
while not future.done():
    status = future.status  # Получаем текущий статус задачи, который может быть "waiting", "running", "finished" и т.д.
    print(f"Current status: {status}")  # Выводим текущий статус задачи.
    time.sleep(2)  # Пауза на 2 секунды перед следующим циклом проверки, чтобы не загружать процессор.

# Получаем результат после завершения задачи.
result = future.result()  # блокирует выполнение до тех пор, пока задача не завершится.
# Когда задача завершена, этот метод возвращает результат выполнения задачи (в данном случае строку, которую мы возвращаем в функции).
print(result)  # Выводим результат выполнения задачи.
