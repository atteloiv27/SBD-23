import seaborn as sns  # Импортируем библиотеку seaborn для удобной визуализации данных.
import matplotlib.pyplot as plt  # Импортируем matplotlib для построения графиков.
import pandas as pd  # Импортируем pandas для работы с данными в формате DataFrame (хотя здесь pandas используется косвенно, через seaborn).

# Данные об ирисе Фишера
iris = sns.load_dataset('iris')  # Загружаем встроенный датасет 'iris' с помощью функции load_dataset из библиотеки seaborn. Этот датасет содержит данные о различных сортах ирисов, включая их физические характеристики.

# Гистограмма для длины чашелистика
plt.figure(figsize=(10, 6))  # Создаем фигуру с заданными размерами (ширина 10 дюймов, высота 6 дюймов).
sns.histplot(iris['sepal_length'], bins=20, kde=True)  # Строим гистограмму для столбца 'sepal_length' (длина чашелистика) из датасета iris.
# Параметры:
# - bins=20: Указывает, что гистограмма будет разделена на 20 корзин (или интервалов) для распределения данных.
# - kde=True: Включает линию плотности вероятности (Kernel Density Estimation), которая помогает визуализировать, как данные распределяются.
plt.title('Гистограмма длины чашелистика ириса Фишера')  # Добавляем заголовок графика, который описывает, что изображена гистограмма длины чашелистика.
plt.xlabel('Длина чашелистика (см)')  # Подписываем ось X, чтобы указать, что на ней отображается длина чашелистика в сантиметрах.
plt.ylabel('Частота')  # Подписываем ось Y, которая показывает частоту (количество наблюдений) для каждой длины чашелистика.
plt.grid(True)  # Включаем отображение сетки на графике, чтобы линии графика было проще воспринимать.
plt.show()  # Показываем график на экране.
