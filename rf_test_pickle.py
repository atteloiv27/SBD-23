import time  # Импортируем модуль time для замера времени выполнения
from functools import wraps  # Импортируем wraps из functools для корректного оформления декораторов
import pickle  # Импортируем pickle для десериализации (загрузки) объектов Python

# Декоратор, который выводит время выполнения функции
def timethis(func):
    @wraps(func)  # Применяем wraps, чтобы сохранить метаданные функции (например, её имя)
    def wrapper(*args, **kwargs):  # Обертка для функции, которая замеряет её время выполнения
        start = time.time()  # Засекаем время начала выполнения
        result = func(*args, **kwargs)  # Вызываем оригинальную функцию и сохраняем её результат
        end = time.time()  # Засекаем время окончания выполнения
        # Печатаем время выполнения функции с точностью до 8 знаков после запятой
        print(f"{func.__name__} выполнен за {end - start:.8f} секунд")
        return result  # Возвращаем результат работы функции
    return wrapper  # Возвращаем функцию-обертку

@timethis  # Применяем декоратор timethis для замера времени выполнения функции
def load_model(filename):
    with open(filename, 'rb') as f:  # Открываем файл с моделью в бинарном режиме для чтения
        return pickle.load(f)  # Десериализуем (загружаем) модель из файла и возвращаем её

rf1 = load_model("rf_model.pkl")  # Загружаем модель из файла "rf_model.pkl" и сохраняем её в переменную rf1

input_data = [[1, 2, 2]]  # Пример входных данных, для которых нужно сделать прогноз (матрица признаков)
prediction = rf1.predict(input_data)  # Используем загруженную модель для предсказания на основе input_data
print(f"Прогноз для {input_data}: {prediction}")  # Печатаем результат прогноза
