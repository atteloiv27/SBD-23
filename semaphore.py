import threading  # Импортируем модуль threading для работы с многозадачностью и многопоточностью

# Создаем семафор с начальным значением 3
# Семафор управляет количеством потоков, которые могут одновременно получить доступ к ресурсу.
# Здесь максимум 3 потока могут работать с ресурсом одновременно.
semaphore = threading.Semaphore(3)  

def worker():
    # Захватываем семафор, уменьшая его счетчик
    # Если счетчик семафора больше 0, поток продолжает выполнение, если нет — ждет.
    semaphore.acquire()  
    try:
        # Выполняем некоторую работу с общим ресурсом
        # В данном примере это просто цикл, выполняющий вычисления
        for i in range(100_000_000):
            a = 1 + i  # Простейшая операция для имитации работы
        # Выводим сообщение, чтобы показать, что поток работает
        print(f"{threading.current_thread().getName()} is working")
    finally:
        # После завершения работы освобождаем семафор, увеличивая его счетчик
        # Это позволяет другим потокам захватить семафор и начать работать с ресурсом.
        semaphore.release()  

# Создаем список для хранения потоков
threads = []
for i in range(10):
    # Создаем новый поток, который будет выполнять функцию worker
    # У каждого потока будет уникальное имя вида "Thread-1", "Thread-2", ...
    thread = threading.Thread(target=worker, name=f"Thread-{i+1}")
    threads.append(thread)  # Добавляем поток в список
    thread.start()  # Запускаем поток

# Ожидаем завершения всех потоков
for thread in threads:
    thread.join()  # Ожидаем завершения работы каждого потока перед продолжением программы
